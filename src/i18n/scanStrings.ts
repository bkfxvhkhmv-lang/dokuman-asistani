const dict: Record<string, Dict> = { tr, de, en };

export function scanT(lang: string, key: string, vars?: Record<string, string>): string {
  const base = dict[lang] ?? dict.en;
  const template = base[key] ?? dict.en[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replace(new RegExp(`\\{${k}\\}`, 'g'), v), template);
}
